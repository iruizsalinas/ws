local H = require("tests.helper")
local ws = require("ws")

H.test("invalid arguments raise", function()
  H.raises(function() ws.connect() end, "url must be a string")
  H.raises(function() ws.connect("http://x") end, "URL scheme must be ws or wss")
  H.raises(function() ws.connect("ws://x", { nope = 1 }) end, "unknown option 'nope'")
  H.raises(function() ws.connect("ws://x", { timeout = 0 }) end, "option 'timeout' must be")
  H.raises(function() ws.connect("ws://x", { protocols = "a b" }) end, "option 'protocols' must be")
  H.raises(function() ws.connect("ws://x", { headers = { Host = "y" } }) end, "header is managed by ws")
  H.raises(function() ws.connect("wss://x", { tls = { ca = "missing.pem" } }) end, "missing.pem")
  H.raises(function() ws.connect("ws://x", { tls = {} }) end, "option 'tls' needs a wss:// URL")
  H.raises(function() ws.connect("wss://x", { ca = "ca.pem" }) end, "unknown option 'ca'")
  H.raises(function() ws.connect("wss://x", { tls = { cert = "a.pem" } }) end, "unknown option 'tls.cert'")
  H.raises(function() ws.listen({}) end, "option 'port' is required")
  H.raises(function() ws.listen({ port = 70000 }) end, "option 'port' must be")
  H.raises(function() ws.listen({ port = 0, limits = { connections = 0 } }) end, "option 'limits.connections' must be")
  H.raises(function() ws.listen({ port = 0, limits = { connections = 1.5 } }) end, "option 'limits.connections' must be")
  H.raises(function() ws.listen({ port = 0, limits = 1000 }) end, "option 'limits' must be a table")
  H.raises(function() ws.connect("ws://x", { limits = { message = 0 } }) end, "option 'limits.message' must be")
  H.raises(function() ws.connect("ws://x", { limits = { buffer = 0 } }) end, "option 'limits.buffer' must be")
  H.raises(function() ws.listen({ port = 0, limits = { buffer = -1 } }) end, "option 'limits.buffer' must be")
  for _, bad in ipairs({ 0, -1, true, "30", 0 / 0, math.huge, 2e6 }) do
    H.raises(function() ws.connect("ws://x", { heartbeat = bad }) end, "option 'heartbeat' must be")
    H.raises(function() ws.listen({ port = 0, heartbeat = bad }) end, "option 'heartbeat' must be")
  end
  ws.listen({ port = 0, heartbeat = false }):close()
  ws.listen({ port = 0, heartbeat = 0.5 }):close()
  H.raises(function() ws.connect("ws://x", { limits = { connections = 1 } }) end, "unknown option 'limits.connections'")
  H.raises(function() ws.connect("ws://x", { limit = 1000 }) end, "unknown option 'limit'")
  H.raises(function() ws.listen({ port = 0, tls = { cert = "a.pem" } }) end, "options 'tls.cert' and 'tls.key' go together")
  H.raises(function() ws.listen({ port = 0, tls = {} }) end, "options 'tls.cert' and 'tls.key' go together")
  H.raises(function() ws.listen({ port = 0, cert = "a.pem" }) end, "unknown option 'cert'")
  H.raises(function() ws.listen({ port = 0, tls = { ca = "c.pem" } }) end, "unknown option 'tls.ca'")
  H.raises(function() ws.listen("x") end, "option 'port' must be")
end)

H.test("socket misuse raises", function()
  local server = H.server()
  server:on("connection", function(c) c:on("close", function() server:close() end) end)
  local c = ws.connect(H.url(server))
  H.raises(function() c:on("nope", print) end, "unknown event 'nope'")
  H.raises(function() c:on("open", 1) end, "listener must be a function")
  H.raises(function() c:once("nope", print) end, "unknown event 'nope'")
  H.raises(function() c:off("open") end, "listener must be a function")
  H.raises(function() server:once("open", print) end, "unknown event 'open'")
  -- Errors blame the caller, not the library.
  H.raises(function() server:off("connection", 1) end, "errors.lua:")
  c:on("open", function()
    H.raises(function() c:send(42) end, "data must be a string")
    H.raises(function() c:send("\255") end, "text must be valid UTF-8")
    H.raises(function() c:ping(string.rep("x", 126)) end, "at most 125 bytes")
    H.raises(function() c:close(1005) end, "invalid close code")
    for _, code in ipairs({ 1000.5, "1000", math.huge, 0 / 0 }) do
      H.raises(function() c:close(code) end, "invalid close code")
      H.eq(c.state, "open", "invalid close must not change state")
    end
    H.raises(function() c:close(1000, string.rep("x", 124)) end, "at most 123 bytes")
    c:close(1000)
  end)
  H.run()
end)

H.test("protocol options are distinct nonempty tokens in a dense array", function()
  local opts = require("ws.opts")
  for _, protocols in ipairs({ "", "a b", { "chat", "chat" }, { [2] = "chat" }, { named = "chat" } }) do
    H.raises(function() opts.check({ protocols = protocols }, { protocols = "list" }, 1) end,
      "option 'protocols' must be")
  end
  local valid = "!#$%&'*+-.^_`|~09AZaz"
  H.eq(opts.check({ protocols = valid }, { protocols = "list" }, 1).protocols[1], valid)
end)

H.test("native size limits reject negative and nonfinite numbers", function()
  local core = require("ws.core")
  local loop = require("ws.loop")
  for _, size in ipairs({ -1, 0.5, math.huge, 0 / 0 }) do
    H.raises(function() core.connect(loop.hub, "http://invalid", nil, nil, nil, nil, size) end, "invalid size")
    H.raises(function() core.listen(loop.hub, "127.0.0.1", 0, nil, nil, nil, size) end, "invalid size")
  end
end)

H.test("unhandled client errors are raised from ws.run", function()
  local probe = H.server()
  local port = probe.port
  probe:close()
  H.run()
  ws.connect("ws://127.0.0.1:" .. port)
  H.raises(function() H.run(15) end, "cannot connect")
  H.run()
end)

H.test("handled errors are events followed by close", function()
  local probe = H.server()
  local port = probe.port
  probe:close()
  local c = ws.connect("ws://127.0.0.1:" .. port)
  local events = {}
  c:on("error", function(err) events[#events + 1] = err:match("^cannot connect") or err end)
  c:on("close", function(code) events[#events + 1] = code end)
  H.run(15)
  H.eq(events[1], "cannot connect")
  H.eq(events[2], 1006)
end)

H.test("the loop cannot be re-entered", function()
  local t
  t = ws.after(0, function()
    H.raises(function() ws.run() end, "already running")
    H.raises(function() ws.poll() end, "already running")
  end)
  H.run()
  H.eq(t.live, false, "fired")
end)

H.test("listener errors propagate and the loop recovers", function()
  ws.after(0, function() error("from a timer") end)
  H.raises(function() ws.run() end, "from a timer")
  H.eq(ws.poll(), false, "idle afterwards")
end)
